import { GoogleGenerativeAI } from "@google/generative-ai";
import { loadChunks, resolveFolder } from "./scan.js";
import { formatContext, retrieve } from "./retrieve.js";
import type { AskResult } from "./types.js";

const DEFAULT_MODEL = process.env.GEMINI_MODEL || "gemini-3.6-flash";

function requireKey(): string {
  const key = process.env.GEMINI_API_KEY;
  if (!key) {
    throw new Error(
      "GEMINI_API_KEY is not set. Export it or copy .env.example → .env"
    );
  }
  return key;
}

export async function askFolder(
  folderArg: string,
  question: string,
  opts: { k?: number; model?: string } = {}
): Promise<AskResult> {
  const folder = await resolveFolder(folderArg);
  const { chunks, fileCount } = await loadChunks(folder);
  if (!chunks.length) {
    throw new Error(
      `No readable text files found under ${folder}. Supported: md, txt, code, json, yaml…`
    );
  }

  const citations = retrieve(chunks, question, opts.k ?? 8);
  if (!citations.length) {
    return {
      answer:
        "I could not find overlapping passages in this folder for that question. Try different keywords or a broader ask.",
      citations: [],
      model: opts.model || DEFAULT_MODEL,
      folder,
      fileCount,
      chunkCount: chunks.length,
      usedChunks: 0,
    };
  }

  const modelName = opts.model || DEFAULT_MODEL;
  const genAI = new GoogleGenerativeAI(requireKey());
  const model = genAI.getGenerativeModel({ model: modelName });

  const context = formatContext(citations);
  const prompt = `You are Desk, a local folder agent. Answer ONLY using the numbered sources below.
If the sources do not support an answer, say so clearly — do not invent facts from outside the folder.
Cite sources inline like [1], [2] matching the numbers.

SOURCES:
${context}

QUESTION: ${question}

ANSWER (markdown, concise, with citations):`;

  const result = await model.generateContent(prompt);
  const answer = result.response.text().trim();

  return {
    answer,
    citations,
    model: modelName,
    folder,
    fileCount,
    chunkCount: chunks.length,
    usedChunks: citations.length,
  };
}

export function renderAskMarkdown(r: AskResult, question: string): string {
  const lines: string[] = [
    `# Desk report`,
    ``,
    `- **Folder:** \`${r.folder}\``,
    `- **Question:** ${question}`,
    `- **Model:** ${r.model}`,
    `- **Files scanned:** ${r.fileCount} · chunks ${r.chunkCount} · used ${r.usedChunks}`,
    ``,
    `## Answer`,
    ``,
    r.answer,
    ``,
    `## Sources`,
    ``,
  ];
  if (!r.citations.length) {
    lines.push("_No overlapping passages retrieved._");
  } else {
    for (let i = 0; i < r.citations.length; i++) {
      const c = r.citations[i]!;
      lines.push(
        `### [${i + 1}] \`${c.relPath}:${c.startLine}-${c.endLine}\` (score ${c.score})`
      );
      lines.push(``);
      lines.push("```");
      lines.push(c.excerpt);
      lines.push("```");
      lines.push(``);
    }
  }
  lines.push(`---`);
  lines.push(`_Generated by Desk — local-first folder agent_`);
  return lines.join("\n");
}
